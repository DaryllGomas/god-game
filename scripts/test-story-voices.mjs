// New Lumi and Fizz story lines get their clips: `npm run build && atlas-run dist scripts/test-story-voices.mjs <out>`.
import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM,args:['--use-gl=angle','--enable-gpu','--ignore-gpu-blocklist','--use-angle=vulkan','--autoplay-policy=no-user-gesture-required']});
const p = await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[], requests=[];
p.on('pageerror',e=>errors.push(String(e)));
p.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
p.on('request',r=>{if(r.url().includes('/voice/')&&r.url().endsWith('.mp3'))requests.push(r.url());});
await p.goto(process.env.SITE_URL+'/index.html?shot=default');
await p.waitForFunction(()=>window.game);
await p.evaluate(()=>{for(const s of document.querySelectorAll('style'))if(s.textContent.includes('visibility: hidden !important'))s.remove();});
await p.getByText('Begin',{exact:false}).first().click({timeout:5000});
await p.mouse.move(800,600);
await p.waitForTimeout(800);
await p.evaluate(()=>{game.audio.unlock();game.audio.setMuted(false);window.clipPlays=[];const play=game.audio.playAdvisorClip.bind(game.audio);game.audio.playAdvisorClip=(c)=>{const stop=play(c);window.clipPlays.push({duration:c.duration,started:!!stop});return stop;};game.hud.toggleHelp(false);game.prayerSystem.advisors.setMuted(false);game.prayerSystem.advisors.say({who:'spirit',text:'Every temple is standing. Can you feel the whole island humming?'},{pri:'important',cooldown:0});});
await p.waitForFunction(()=>document.querySelector('.adv-card.show.spirit'),null,{timeout:20000}).catch(async e=>{await p.screenshot({path:process.env.OUT_DIR+'/fail.png'});console.log(JSON.stringify(await p.evaluate(()=>{const a=game.prayerSystem.advisors;return {showing:a.showing,q:a.queue.length,muted:a.muted,figs:[...document.querySelectorAll('.adv-figure')].map(e=>e.className)}})),errors);throw e;});
await p.waitForTimeout(600);
await p.evaluate(()=>{const a=game.prayerSystem.advisors;a.finish();a.queue.length=0;game.hand.valid=false;a.say({who:'imp',text:'Are we sightseeing? I love sightseeing.'},{pri:'important',cooldown:0});});
await p.mouse.move(0,0);
await p.waitForFunction(()=>document.querySelector('.adv-card.show.imp'));
await p.waitForTimeout(600);
await p.screenshot({path:process.env.OUT_DIR+'/fizz.png'});
const clips=await p.evaluate(()=>window.clipPlays);
await fs.writeFile(process.env.OUT_DIR+'/evidence.json',JSON.stringify({errors,requests,clips},null,2));
await browser.close();
const has=(n)=>requests.some(r=>r.endsWith('/'+n+'.mp3'));
if(errors.length||!has('lumi-a8423b73')||!has('fizz-3293943d')||clips.filter(c=>c.started).length<2)throw Error('Evidence check failed: '+JSON.stringify({errors,requests,clips}));
