import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM,args:['--use-gl=angle','--enable-gpu','--ignore-gpu-blocklist','--use-angle=vulkan','--autoplay-policy=no-user-gesture-required']});
const p = await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[], requests=[];
p.on('pageerror',e=>errors.push(String(e)));
p.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
p.on('request',r=>{if(r.url().includes('/voice/'))requests.push(r.url());});
await p.addInitScript(()=>{
 window.voiceStarts=[];
 const start=AudioBufferSourceNode.prototype.start;
 AudioBufferSourceNode.prototype.start=function(...args){if(this.buffer && !this.loop)window.voiceStarts.push({duration:this.buffer.duration,rate:this.buffer.sampleRate,time:performance.now()});return start.apply(this,args);};
 window.emptySpeech=[];
 setInterval(()=>{for(const el of document.querySelectorAll('.adv-card.show .adv-text,.adv-figure.show .adv-speech.show .adv-text'))if(!el.textContent.trim())window.emptySpeech.push(el.outerHTML);},16);
});
await p.goto(process.env.SITE_URL+'/index.html?shot=default');
await p.waitForFunction(()=>window.game);
await p.evaluate(()=>{for(const s of document.querySelectorAll('style'))if(s.textContent.includes('visibility: hidden !important'))s.remove();});
await p.getByText('Begin',{exact:false}).first().click({timeout:5000});
await p.mouse.move(800,600);
await p.waitForTimeout(800);
await p.evaluate(()=>{game.audio.unlock();game.audio.setMuted(false);window.clipPlays=[];const play=game.audio.playAdvisorClip.bind(game.audio);game.audio.playAdvisorClip=(clip)=>{const stop=play(clip);window.clipPlays.push({duration:clip.duration,started:!!stop});return stop;};game.prayerSystem.advisors.setMuted(false);game.prayerSystem.advisors.say([{who:'spirit',text:'Lovely! A new roof means a happy family.'}],{pri:'important',cooldown:0});});
await p.waitForFunction(()=>document.querySelector('.adv-figure.spirit.show .adv-speech.show'));
await p.waitForTimeout(500);
await p.screenshot({path:process.env.OUT_DIR+'/lumi.png'});
const lumi=await p.evaluate(()=>({life:game.prayerSystem.advisors.cardLife,text:document.querySelector('.adv-figure.spirit .adv-text').textContent,hand:game.hand.pos.clone().project(game.godCam.camera).toArray(),figures:[...document.querySelectorAll('.adv-figure')].map(el=>({class:el.className,rect:el.getBoundingClientRect().toJSON()}))}));
await p.evaluate(()=>{const a=game.prayerSystem.advisors;a.finish();a.queue.length=0;game.hand.valid=false;a.say({who:'imp',text:'Bread diplomacy. Very effective.'},{pri:'important',cooldown:0});});
await p.mouse.move(0,0);
await p.waitForFunction(()=>document.querySelector('.adv-card.show'));
await p.screenshot({path:process.env.OUT_DIR+'/fallback.png'});
await p.evaluate(()=>game.hud.toggleHelp(true));
await p.waitForTimeout(200);
const help=await p.evaluate(()=>({showing:game.prayerSystem.advisors.showing,visible:document.querySelectorAll('.adv-card.show,.adv-figure.show').length}));
await p.evaluate(()=>game.hud.toggleHelp(false));
await p.mouse.move(800,600);
await p.evaluate(()=>{const a=game.prayerSystem.advisors;a.finish();a.queue.length=0;const v=game.entities.find(e=>e.kind==='villager');game.hand.held=v;v.held=true;a.holding=5;a.watchTemptation(0.1);});
await p.waitForFunction(()=>document.querySelectorAll('.adv-figure.show').length===2 && document.querySelector('.adv-figure.imp .adv-speech.show'));
await p.waitForTimeout(500);
await p.screenshot({path:process.env.OUT_DIR+'/argument-fizz.png'});
const first=await p.locator('.adv-figure.imp .adv-text').textContent();
await p.waitForFunction(()=>document.querySelector('.adv-figure.spirit .adv-speech.show'),{timeout:20000});
await p.waitForTimeout(500);
await p.screenshot({path:process.env.OUT_DIR+'/argument-lumi.png'});
const second=await p.locator('.adv-figure.spirit .adv-text').textContent();
// The destructive deed takes priority over the temptation's remaining exchange.
await p.evaluate(()=>game.events.emit('houseDestroyed',{byPlayer:true,house:game.villages[0].houses[0]}));
await p.waitForFunction(()=>document.querySelector('.adv-figure.imp .adv-text').textContent==='Smashing! Literally.' && document.querySelector('.adv-figure.imp .adv-speech.show'));
const reaction=await p.locator('.adv-figure.imp .adv-text').textContent();
// Exact cached text should not fetch twice, and empty offers must never enter the queue.
const rejectedEmpty=await p.evaluate(()=>{const a=game.prayerSystem.advisors;a.finish();a.queue.length=0;const accepted=a.say({who:'spirit',text:'   '},{pri:'important',cooldown:0});a.say({who:'spirit',text:'Lovely! A new roof means a happy family.'},{pri:'important',cooldown:0});return !accepted;});
await p.waitForFunction(()=>document.querySelector('.adv-figure.spirit .adv-speech.show'));
await p.evaluate(()=>{game.hand.held.held=false;game.hand.held=null;game.prayerSystem.advisors.setMuted(true);});
const result=await p.evaluate(()=>({starts:window.voiceStarts,clips:window.clipPlays,empty:window.emptySpeech}));
await fs.writeFile(process.env.OUT_DIR+'/evidence.json',JSON.stringify({errors,requests,lumi,help,argument:[first,second],reaction,rejectedEmpty,...result},null,2));
await browser.close();
if(!rejectedEmpty||requests.filter(r=>r.endsWith('/lumi-9672eae3.mp3')).length!==1||errors.length||result.empty.length||requests.filter(r=>r.endsWith('.mp3')).length<4||result.clips.filter(c=>c.started && result.starts.some(s=>s.duration===c.duration)).length<4||help.showing||help.visible)throw Error('Evidence check failed');
